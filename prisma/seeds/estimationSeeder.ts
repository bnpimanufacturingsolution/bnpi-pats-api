// Helper function to generate default fields for items
function generateDefaultFields(itemName: string, type: "CAPEX" | "OPEX") {
	const commonFields = [
		{ fieldId: FIELD_IDS.PRIORITY_LEVEL, value: Math.floor(Math.random() * 5) + 1 },
		{ fieldId: FIELD_IDS.RISK_LEVEL, value: ["Low", "Medium", "High"][Math.floor(Math.random() * 3)] },
		{ fieldId: FIELD_IDS.DEPARTMENT, value: type === "CAPEX" ? "Infrastructure" : "Operations" },
		{ fieldId: FIELD_IDS.TAGS, value: [type, "Project"] },
	];

	const customFields = [
		{
			fieldId: FIELD_IDS.NOTES,
			value: `Standard ${type} item for ${itemName}`,
		},
	];

	return {
		common: commonFields,
		custom: customFields,
	};
}

